/**
     * Export authors to CSV.
     */
    public function export(Request $request)
    {
        $query = Author::withCount('books');

        if ($request->has('status')) {
            $query->where('status', $request->status === 'active' ? 1 : 0);
        }

        $authors = $query->get();

        $filename = 'authors_' . date('Y-m-d_His') . '.csv';
        $path = storage_path('app/public/exports/' . $filename);

        if (!is_dir(dirname($path))) {
            mkdir(dirname($path), 0755, true);
        }

        $file = fopen($path, 'w');

        fputcsv($file, [
            'ID', 'Name', 'Slug', 'Email', 'Website',
            'Books Count', 'Status', 'Created At', 'Updated At'
        ]);

        foreach ($authors as $author) {
            fputcsv($file, [
                $author->id,
                $author->name,
                $author->slug,
                $author->email ?? '',
                $author->website ?? '',
                $author->books_count,
                $author->status ? 'Active' : 'Inactive',
                $author->created_at->format('Y-m-d H:i:s'),
                $author->updated_at->format('Y-m-d H:i:s'),
            ]);
        }

        fclose($file);

        return response()->download($path, $filename)->deleteFileAfterSend(true);
    }
}
